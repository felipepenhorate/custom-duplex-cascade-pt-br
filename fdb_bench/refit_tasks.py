"""Re-run selected FDB tasks for an existing run and splice them back in.

Scenario fixes should not force a full 727-scenario re-run per model. This
re-runs only the named tasks and replaces exactly those rows in ``raw.jsonl``,
leaving the other tasks untouched, then reports what changed.

    # after changing the pause scenarios:
    python -m fdb_bench.refit_tasks --run results/pt/sft --model sft \
        --tasks pause_synthetic,pause_candor --api-base http://127.0.0.1:8098/v1

``meta.json`` is left alone (the scenario count does not change); the run's
``summary.md``/``summary.json`` are regenerated by ``run_metrics.py``.
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

from . import protocol as P
from . import scenarios as S
from .adapters import build_adapter
from .clock import SpeechClock
from .run_inference import _serialise, build_chunker
from .simulate import DuplexSimulator


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run", required=True, type=Path,
                    help="a run_inference.py --out directory (has raw.jsonl)")
    ap.add_argument("--model", required=True, choices=sorted(P.MODEL_REGISTRY))
    ap.add_argument("--tasks", required=True,
                    help="comma-separated subset names to re-run")
    ap.add_argument("--lang", default="pt", choices=S.LANGS)
    ap.add_argument("--api-base", default="http://127.0.0.1:8080/v1")
    ap.add_argument("--big-api-base", default=None)
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--prompt-candidate", default=None)
    ap.add_argument("--prime-mode", default="decision")
    ap.add_argument("--words-per-second", type=float, default=3.25)
    ap.add_argument("--seed", type=int, default=None,
                    help="defaults to the seed recorded in meta.json")
    ap.add_argument("--limit", type=int, default=None)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    tasks = tuple(t.strip() for t in args.tasks.split(",") if t.strip())
    for t in tasks:
        if t not in S.TASKS:
            raise SystemExit(f"unknown task {t!r}; expected {S.TASKS}")

    raw_path = args.run / "raw.jsonl"
    if not raw_path.is_file():
        raise SystemExit(f"no raw.jsonl in {args.run}")
    rows = [json.loads(l) for l in raw_path.read_text(encoding="utf-8").splitlines()
            if l.strip()]
    before = {t: sum(1 for r in rows if r["task"] == t) for t in tasks}
    print(f"existing rows: {len(rows)}; replacing {before}")

    meta = {}
    mp = args.run / "meta.json"
    if mp.is_file():
        meta = json.loads(mp.read_text())
    seed = args.seed if args.seed is not None else meta.get("seed", 1234)
    # reuse whatever configuration produced the rest of the run, unless overridden
    candidate = args.prompt_candidate or meta.get("prompt_candidate")
    wps = args.words_per_second or meta.get("words_per_second", 3.25)
    print(f"config: candidate={candidate!r} seed={seed} wps={wps}")

    adapter = build_adapter(
        args.model, api_base=args.api_base, big_api_base=args.api_base,
        device=args.device, lang=args.lang, prompt_candidate=candidate,
        prime_mode=args.prime_mode,
    )
    sim = DuplexSimulator(adapter, SpeechClock(wps))
    chunker = build_chunker()

    t0 = time.time()
    new_rows: list[dict] = []
    for task in tasks:
        scs = S.build_scenarios(task, limit=args.limit, seed=seed,
                                lang=args.lang, chunker=chunker)
        for i, sc in enumerate(scs):
            r = sim.run(sc)
            r.compute_s = getattr(adapter, "last_call_s", 0.0)
            new_rows.append(_serialise(r))
            if (i + 1) % 25 == 0:
                print(f"  {task}: {i+1}/{len(scs)} "
                      f"({(time.time()-t0)/(len(new_rows)):.2f}s/scenario)", flush=True)

    if args.dry_run:
        print(f"dry run: would write {len(new_rows)} rows")
        return

    kept = [r for r in rows if r["task"] not in tasks]
    backup = raw_path.with_suffix(".jsonl.bak")
    backup.write_text(raw_path.read_text(encoding="utf-8"), encoding="utf-8")
    raw_path.write_text(
        "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in kept + new_rows),
        encoding="utf-8",
    )
    print(f"wrote {raw_path}: {len(kept)} kept + {len(new_rows)} new = "
          f"{len(kept) + len(new_rows)} rows (backup: {backup})")


if __name__ == "__main__":
    main()
